import {test,expect} from '@playwright/test';
import {readFile} from 'node:fs/promises';
const settings=JSON.parse(await readFile(new URL('../../tests/.runtime/settings.json',import.meta.url),'utf8'));
for(const width of [1440,360])test(`documentos reales y saldo inicial a ${width}px`,async({page,context})=>{
  await page.setViewportSize({width,height:1000});
  await page.goto('/');await page.locator('#username').fill('gestor-local');
  await page.locator('#password').fill(settings.TEST_OWNER_PASSWORD);
  await page.getByRole('button',{name:'Entrar a mi portal'}).click();
  await expect(page.locator('#month')).toBeVisible();
  const call=async(path,method='GET',body)=>page.evaluate(async({path,method,body})=>{
    const response=await fetch('/api/v1'+path,{method,headers:{'Content-Type':'application/json'},body:body===undefined?undefined:JSON.stringify(body)});
    if(!response.ok)throw new Error(`${response.status} ${path}`);return response.json();
  },{path,method,body});
  const suffix=Date.now();
  const building=await call('/edificios','POST',{nombre:`Saldo ${suffix}`});
  const property=await call('/propiedades','POST',{nombre:`Vivienda ${suffix}`,edificioId:building.id});
  const tenant=await call('/inquilinos','POST',{nombre:`Saldo ${suffix}`,propiedadId:property.id,renta:'600.00',dni:'PRUEBA',fianza:'600.00',inicio:'2020-01-01'});
  const emptyProperty=await call('/propiedades','POST',{nombre:`Sin inquilino ${suffix}`,edificioId:building.id});
  const secondProperty=await call('/propiedades','POST',{nombre:`Segunda vivienda ${suffix}`,edificioId:building.id});
  const secondTenant=await call('/inquilinos','POST',{nombre:`Segundo inquilino ${suffix}`,propiedadId:secondProperty.id,dni:'PRUEBA',renta:'0.00',fianza:'0.00',inicio:'2020-01-01'});
  const period=await page.locator('#month').inputValue();
  let rows=await call(`/pagos?mes=${period}`);
  expect(rows.data.find(row=>row.inquilinoId===tenant.id)).toMatchObject({amountDue:'600.00',amountPaid:'0.00',balance:'600.00'});
  for(const [paid,balance,version] of [['250.00','350.00',0],['600.00','0.00',1]]){
    const payment=await call(`/inquilinos/${tenant.id}/pagos/${period}`,'PUT',{amountPaid:paid,version});expect(payment.balance).toBe(balance);
  }
  await page.getByRole('button',{name:'Documentos',exact:true}).click();
  await page.getByRole('button',{name:'Nuevo documento'}).click();
  const name=`Contrato adjunto ${suffix}`;
  await page.getByLabel('Nombre *',{exact:true}).fill(name);
  await page.getByLabel('Tipo *',{exact:true}).selectOption('contrato');
  const propertySelect=page.getByLabel('Propiedad *',{exact:true});
  const tenantSelect=page.getByLabel('Inquilino *',{exact:true});
  await expect(propertySelect.locator(`option[value="${emptyProperty.id}"]`)).toHaveCount(0);
  await propertySelect.selectOption(property.id);await expect(tenantSelect).toHaveValue(tenant.id);
  await tenantSelect.selectOption(secondTenant.id);await expect(propertySelect).toHaveValue(secondProperty.id);
  await tenantSelect.selectOption('');await expect(propertySelect).toHaveValue('');
  await tenantSelect.selectOption(tenant.id);await expect(propertySelect).toHaveValue(property.id);
  const bytes=Buffer.alloc(100000,65); // Exceeds the ordinary JSON body limit.
  await page.locator('input[type=file]').setInputFiles({name:'Contrato José.pdf',mimeType:'application/pdf',buffer:bytes});
  await page.getByRole('button',{name:'Guardar',exact:true}).click();
  const card=page.locator('.record-card').filter({has:page.getByRole('heading',{name,exact:true})});
  const link=card.getByRole('link',{name:/Descargar/});await expect(link).toContainText('Contrato José.pdf');
  const url=await link.getAttribute('href');
  let response=await context.request.get(url);expect(response.status()).toBe(200);expect(await response.body()).toEqual(bytes);
  expect(response.headers()['content-disposition']).toContain('attachment');
  await page.reload();await page.getByRole('button',{name:'Documentos',exact:true}).click();await expect(link).toBeVisible();
  const oldVersion=await call(url.replace('/api/v1','').replace('/archivo',''));
  expect(oldVersion).toMatchObject({propiedadId:property.id,inquilinoId:tenant.id});
  await card.getByRole('button',{name:'Editar'}).click();
  await page.locator('input[type=file]').setInputFiles({name:'Actualizado.txt',mimeType:'text/plain',buffer:Buffer.from('Documento sustituido')});
  await page.getByRole('button',{name:'Guardar',exact:true}).click();await expect(link).toContainText('Actualizado.txt');
  response=await context.request.get(url);expect((await response.body()).toString()).toBe('Documento sustituido');
  const document={nombre:name,tipo:'contrato',propiedadId:property.id,inquilinoId:tenant.id};
  const stale=await context.request.put(url,{headers:{Origin:'http://127.0.0.1:55173','x-document-metadata':JSON.stringify({document,filename:'Viejo.txt',version:oldVersion.version})},data:Buffer.from('No sobrescribir')});
  expect(stale.status()).toBe(409);
  const metadata={document,filename:'Grande.pdf',version:oldVersion.version+1};
  const mismatched=await context.request.put(url,{headers:{Origin:'http://127.0.0.1:55173','x-document-metadata':JSON.stringify({...metadata,document:{...document,propiedadId:emptyProperty.id}})},data:Buffer.from('No sobrescribir')});
  expect(mismatched.status()).toBe(400);
  const tooLarge=await context.request.put(url,{headers:{Origin:'http://127.0.0.1:55173','x-document-metadata':JSON.stringify(metadata)},data:Buffer.alloc(10*1024*1024+1,65)});
  expect(tooLarge.status()).toBe(413);
  const invalid=await context.request.put(url,{headers:{Origin:'http://127.0.0.1:55173','x-document-metadata':JSON.stringify({...metadata,filename:'../archivo.txt'})},data:Buffer.from('Invalido')});
  expect(invalid.status()).toBe(400);
  expect((await (await context.request.get(url)).body()).toString()).toBe('Documento sustituido');
  await page.screenshot({path:`../tests/artifacts/frontend/documentos-${width}.png`,fullPage:true});
  expect(await page.evaluate(()=>document.documentElement.scrollWidth)).toBeLessThanOrEqual(width);
  await card.getByRole('button',{name:'Archivar',exact:true}).click();await page.getByRole('button',{name:'Guardar',exact:true}).click();
  await expect(card).toHaveCount(0);
  expect((await context.request.get(url)).status()).toBe(404);
  await page.getByRole('button',{name:'Cerrar sesión'}).click();expect((await context.request.get(url)).status()).toBe(401);
});
